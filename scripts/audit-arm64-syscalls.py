#!/usr/bin/env python3
"""Generate source-coverage inventory; never infer conformance from a handler."""
from pathlib import Path
import re,json,collections
repo=Path(__file__).resolve().parents[1]
ref=json.loads((repo/'docs/aarch64-syscall-reference.json').read_text())
entries={}
for line in (repo/'kernel/arch/arm64/calls.c').read_text().splitlines():
 m=re.match(r'\s*\[(\d+)(?:\s*\.\.\.\s*(\d+))?\]\s*=\s*\(syscall_t\)\s*(\w+)',line)
 if m:
  for n in range(int(m[1]),int(m[2] or m[1])+1): entries[n]=m[3]
locations={}
for base in ['kernel','fs']:
 for p in (repo/base).rglob('*.c'):
  if 'arch' in p.parts and 'arm64' not in p.parts:continue
  text=p.read_text()
  for m in re.finditer(r'^(?:static\s+)?[A-Za-z_][\w *]+\b(\w+)\([^;{}]*\)\s*\{',text,re.M):
   ln=text.count('\n',0,m.start())+1
   locations.setdefault(m[1],f'{p.relative_to(repo)}:{ln}')
wrong={'sys_prctl':'Implemented but incomplete: tested dumpability/no_new_privs; keepcaps stub and other options missing',
'sys_capget':'Incorrect behavior: success without capability data','sys_capset':'Incorrect behavior: no capability update',
'sys_inotify_add_watch':'Incorrect behavior: fake watch, no events','sys_inotify_rm_watch':'Incorrect behavior: no watch lifecycle',
'sys_mlock':'Incorrect behavior: success stub','sys_msync':'Incorrect behavior: success stub','sys_mbind':'Incorrect behavior: success stub',
'sys_membarrier':'Incorrect behavior: advertised cross-thread barrier missing','sys_rseq':'Implemented but incomplete: no abort handling',
'sys_sched_setaffinity':'Incorrect behavior: ignores arguments','sys_ioprio_set':'Incorrect behavior: ignores arguments',
'sys_mq_notify':'Incorrect behavior: notification absent','sys_semctl':'Implemented but incomplete: IPC metadata/undo/counts',
'sys_memfd_create':'Implemented but incomplete: sealing missing'}
verified={'sys_sendmsg':'Implemented and verified (Mac bounded SCM/lifetime/64-bit-iovec contract; other socket paths incomplete)',
'sys_recvmsg':'Implemented and verified (Mac SCM truncation/lifetime contract; stream fault retention incomplete)',
'sys_faccessat_legacy':'Implemented and verified (Mac raw ABI/real-ID contract)',
'sys_eventfd2':'Implemented and verified (Mac semaphore/description/readiness contract)',
'sys_epoll_wait':'Implemented and verified (Mac bounded-batch subset)',
'sys_execveat':'Implemented and verified (Mac guest contract; bounded subset)',
'sys_setgroups':'Implemented and verified (Mac credential contract; max32)',
'sys_setreuid':'Implemented and verified (Mac credential contract)',
'sys_setregid':'Implemented and verified (Mac credential contract)',
'sys_fstatat64':'Implemented and verified (Mac empty-path contract)',
'sys_statx':'Implemented and verified (Mac basic-stat subset)',
'sys_shmctl':'Implemented and verified (Mac ownership/lifetime contracts; bounded subset)',
'sys_shmget':'Implemented and verified (Mac permissions/lifetime contracts)',
'sys_shmat':'Implemented and verified (Mac permissions/lifetime contracts)'}
count=collections.Counter(entries.values())
lines=['# AArch64 syscall matrix','',
'Generated by `python3 scripts/audit-arm64-syscalls.py`. Named ABI reference: Linux v6.12 `scripts/syscall.tbl` (selection recorded in `aarch64-syscall-reference.json`).',
f'Reference SHA256: `{ref["reference_sha256"]}`. Dispatch source: `kernel/arch/arm64/calls.c`.',
'',f'{len(entries)} explicit entries / {max(entries)+1} array slots; {len(set(entries.values()))} handler symbols. Missing reserved slots are not counted as missing Linux APIs.',
'Counts describe source dispatch only. A real handler is **Not yet tested** here unless a specific contract is linked; broader application success is not syscall conformance. No new physical-device tests in this audit.',
'', '| Number | Linux name | Handler | Classification / evidence | Source |','|---:|---|---|---|---|']
for n in sorted(set(map(int,ref['names']))|set(entries)):
 h=entries.get(n,'—');name=ref['names'].get(str(n),'not in selected v6.12 ABI')
 if h=='—':state='Missing (ENOSYS outside populated dispatch)'
 elif h in ('syscall_stub','syscall_silent_stub'):state='Missing (explicit ENOSYS); platform restrictions vary'
 elif h=='sys_xattr_stub':state='Missing (ENOTSUP)'
 elif h=='syscall_success_stub':state='Incorrect behavior: success without sync'
 else:state=wrong.get(h,verified.get(h,'Not yet tested at per-call conformance level; inspect handler'))
 lines.append(f'| {n} | {name} | `{h}` | {state} | `{locations.get(h,"kernel/arch/arm64/calls.c")}` |')
lines+=['','Credential/IPC tests: `tests/linuxrunner/credentials_ipc_contract.c`; execution: `execveat_contract.c`; stat: `stat_empty_path_contract.c`. Known limitations are listed under Compatibility and limitations in the README.','']
lines += ['', (repo/'docs/syscall-verified-subsets.md').read_text()]
(repo/'docs/SYSCALL_MATRIX.md').write_text('\n'.join(lines))
print('Generated syscall matrix:',len(entries),'explicit;',len(lines)-14,'approximately named rows')
